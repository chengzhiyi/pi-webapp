const scene = () => ({ ...emptyScene(), elements: [{ id: "input", type: "rectangle", x: 20, y: 30, width: 200, height: 100 }, { id: "text", type: "text", text: "手动修改", containerId: "input", x: 40, y: 50, width: 100, height: 30 }] });
const graph = { nodes: [{ id: "input", label: "输入验证码" }, { id: "check", label: "验证通过？", kind: "decision" }, { id: "success", label: "登录成功" }], edges: [{ id: "e1", from: "input", to: "check" }, { id: "e2", from: "check", to: "success", label: "是" }, { id: "e3", from: "check", to: "input", label: "否，重试" }] };

test("diagram wire validation rejects duplicate IDs, missing endpoints, executable resources and bounds", () => {
  assert.equal(validateGraph(graph).nodes.length, 3);
  assert.throws(() => validateGraph({ ...graph, nodes: [...graph.nodes, graph.nodes[0]] }), /重复/);
  assert.throws(() => validateGraph({ nodes: graph.nodes, edges: [{ id: "e", from: "input", to: "unknown" }] }), /不存在/);
  assert.throws(() => validateGraph({ nodes: Array.from({ length: 31 }, (_, i) => ({ id: `n${i}`, label: "节点" })) }), /30/);
  assert.throws(() => validateGraph({ nodes: [{ id: "node", label: "test", x: Infinity }] }), /坐标/);
  assert.throws(() => validateScene({ ...scene(), files: { png: {} } }), /附件/);
  assert.throws(() => validateScene({ ...scene(), elements: [{ ...scene().elements[0], type: "iframe" }] }), /不支持/);
  assert.throws(() => validateScene({ ...scene(), elements: [{ ...scene().elements[0], link: "https://example.com" }] }), /外链/);
  assert.throws(() => validateScene({ ...scene(), elements: [{ ...scene().elements[0], x: NaN }] }), /数值/);
  assert.throws(() => validateScene({ ...scene(), elements: [{ ...scene().elements[0], points: [[Infinity, 0]] }] }), /坐标/);
  assert.deepEqual(validateScene({ ...scene(), appState: { viewBackgroundColor: "#fff", collaborators: ["secret"], selectedElementIds: { input: true } } }).appState, { viewBackgroundColor: "#fff" });
  assert.equal(validatePatch({ updateNodes: [{ id: "input", label: "新文案" }] }, scene()).updateNodes?.[0]?.id, "input");
  assert.throws(() => validatePatch({ updateNodes: [{ id: "text", label: "wrong" }] }, scene()), /节点不存在/);
  assert.throws(() => validatePatch({ addNodes: [{ id: "input", label: "重复" }] }, scene()), /已存在/);
  assert.throws(() => validatePatch({ removeIds: ["missing"] }, scene()), /不存在/);
});

test("native frames round-trip without permitting web embeds or invalid frame references", () => {
  const framed = { ...scene(), elements: [{ id: "frame", type: "frame", x: 0, y: 0, width: 500, height: 500, name: "核心层" }, ...scene().elements.map(e => ({ ...e, frameId: "frame" }))] };
  assert.deepEqual(validateScene(framed).elements, framed.elements);
  assert.throws(() => validateScene({ ...framed, elements: [{ ...scene().elements[0], frameId: "missing" }] }), /画框引用/);
  assert.throws(() => validateScene({ ...framed, elements: [{ ...framed.elements[0], name: {} }] }), /画框名称/);
  assert.throws(() => validateScene({ ...framed, elements: [{ ...framed.elements[0], type: "embeddable" }] }), /不支持/);
});

test("rich composition preserves safe styling, grouping, paths and targeted edits", () => {
  const graph = validateGraph(architectureExample);
  assert.equal(graph.nodes.filter(n => n.kind === "group").length, 4);
  assert.equal(graph.nodes.find(n => n.id === "title")?.fontSize, 36);
  assert.equal(graph.edges.find(e => e.id === "experimental")?.strokeStyle, "dashed");
  const rich = { nodes: [{ id: "a", label: "A", width: 300 }], edges: [{ id: "e", from: "a", to: "a", waypoints: [[300, 10]], strokeColor: "#aabbcc" }] };
  assert.deepEqual(validateGraph(rich).edges[0]?.waypoints, [[300, 10]]);
  for (const input of [{ fontSize: 300 }, { width: -2 }, { strokeColor: "url(https://evil.example)" }, { strokeStyle: "script" }, { groupId: "missing" }]) assert.throws(() => validateGraph({ nodes: [{ id: "a", label: "A", ...input }] }));
  assert.throws(() => validateGraph({ nodes: [{ id: "a", label: "A", kind: "text" }], edges: [{ id: "e", from: "a", to: "a" }] }), /不存在/);
  assert.throws(() => validateGraph({ ...rich, edges: [{ ...rich.edges[0], waypoints: [[NaN, 0]] }] }), /途经点/);
  const edit = validatePatch({ updateElements: [{ id: "input", x: 200, backgroundColor: "#ffffff", label: "修改" }] }, scene());
  assert.equal(edit.updateElements?.[0]?.x, 200);
  for (const input of [{ id: "missing", x: 10 }, { id: "text", x: 10 }, { id: "input" }, { id: "input", width: Infinity }]) assert.throws(() => validatePatch({ updateElements: [input] }, scene()));
  assert.throws(() => validatePatch({ updateNodes: [{ id: "input", label: "a" }], updateElements: [{ id: "input", x: 100 }] }, scene()), /重复/);
  const store = new DiagramStore();
  const reference = store.tool("/example", "a", "reference", {}) as { guide: string; example: { graph: unknown } };
  assert.match(reference.guide, /waypoints/);
  assert.equal(validateGraph(reference.example.graph).nodes.length, graph.nodes.length);
});

test("diagram files use scoped paths, exclusive creation, hashes, locks, bounded reads and atomic save", async t => {
  const cwd = await mkdtemp(join(tmpdir(), "pi-diagram-files-")); t.after(() => rm(cwd, { recursive: true, force: true }));
  const firstHash = await saveDiagram(cwd, "diagrams/a.excalidraw", scene(), null);
  assert.equal((await readDiagram(cwd, "diagrams/a.excalidraw")).hash, firstHash);
  await assert.rejects(saveDiagram(cwd, "diagrams/a.excalidraw", emptyScene(), null), /已存在/);
  assert.equal((await readDiagram(cwd, "diagrams/a.excalidraw")).scene.elements[1]?.text, "手动修改");
  const secondHash = await saveDiagram(cwd, "diagrams/a.excalidraw", emptyScene(), firstHash);
  assert.notEqual(secondHash, firstHash);
  await writeFile(join(cwd, "diagrams/a.excalidraw"), JSON.stringify(scene()));
  await assert.rejects(saveDiagram(cwd, "diagrams/a.excalidraw", emptyScene(), secondHash), /外部修改/);
  await assert.rejects(saveDiagram(cwd, "../escape.excalidraw", scene(), null), /越界/);
  await assert.rejects(saveDiagram(cwd, "/tmp/escape.excalidraw", scene(), null), /相对路径/);
  await assert.rejects(saveDiagram(cwd, "C:\\escape.excalidraw", scene(), null), /相对路径/);
  await assert.rejects(saveDiagram(cwd, "script.js", scene(), null), /相对路径/);
  await symlink(join(cwd, "diagrams"), join(cwd, "alias"));
  await assert.rejects(saveDiagram(cwd, "alias/b.excalidraw", scene(), null), /符号链接/);
  await symlink(join(cwd, "diagrams/a.excalidraw"), join(cwd, "link.excalidraw"));
  await assert.rejects(readDiagram(cwd, "link.excalidraw"), /符号链接/);
  await mkdir(join(cwd, "dir.excalidraw"));
  await assert.rejects(readDiagram(cwd, "dir.excalidraw"), /普通文件/);
  await writeFile(join(cwd, "bad.excalidraw"), "{broken"); await assert.rejects(readDiagram(cwd, "bad.excalidraw"), /JSON/);
  await writeFile(join(cwd, "big.excalidraw"), Buffer.alloc(513 * 1024)); await assert.rejects(readDiagram(cwd, "big.excalidraw"), /512/);
  await writeFile(join(cwd, "diagrams/a.excalidraw.lock"), "live lock");
  await assert.rejects(saveDiagram(cwd, "diagrams/a.excalidraw", scene(), firstHash), /正在保存/);
  assert.equal(await readFile(join(cwd, "diagrams/a.excalidraw.lock"), "utf8"), "live lock");
  await assert.rejects(saveDiagram(cwd, "diagrams/new.excalidraw", scene(), null, () => { throw new Error("session changed"); }), /session changed/);
  await assert.rejects(readFile(join(cwd, "diagrams/new.excalidraw")), { code: "ENOENT" });
  const outcomes = await Promise.allSettled([saveDiagram(cwd, "diagrams/race.excalidraw", scene(), null), saveDiagram(cwd, "diagrams/race.excalidraw", emptyScene(), null)]);
  assert.equal(outcomes.filter(r => r.status === "fulfilled").length, 1);
});

test("diagram store separates sessions, protects hand edits and requires explicit candidate acceptance", async t => {
  const cwd = await mkdtemp(join(tmpdir(), "pi-diagram-store-")); t.after(() => rm(cwd, { recursive: true, force: true }));
  const store = new DiagramStore(), guard = () => {};
  const result = store.tool(cwd, "a", "create", { title: "登录流程", graph }) as { id: string; status: string };
  assert.equal(result.status, "pending_canvas_acceptance");
  assert.equal(store.list(cwd, "b").length, 0);
  assert.throws(() => store.tool(cwd, "b", "read", { id: result.id }), /当前会话/);
  let draft = await store.action(cwd, "a", "get", { id: result.id }, guard) as DiagramDraft;
  assert.equal(draft.scene.elements.length, 0);
  await assert.rejects(store.action(cwd, "a", "save", { id: draft.id, revision: 0, path: "diagrams/a.excalidraw" }, guard), /候选/);
  draft = await store.action(cwd, "a", "accept", { id: draft.id, revision: 0, candidateId: draft.candidate!.id, scene: scene() }, guard) as DiagramDraft;
  assert.equal(draft.revision, 1);
  store.tool(cwd, "a", "patch", { id: draft.id, baseRevision: 1, patch: { addNodes: [{ id: "new", label: "新增分支" }] } });
  const before = structuredClone(draft.scene);
  draft = await store.action(cwd, "a", "get", { id: draft.id }, guard) as DiagramDraft;
  assert.deepEqual(draft.scene, before);
  draft = await store.action(cwd, "a", "sync", { id: draft.id, revision: 1, scene: { ...scene(), elements: scene().elements.map(e => ({ ...e, x: e.x + 100 })) } }, guard) as DiagramDraft;
  await assert.rejects(store.action(cwd, "a", "accept", { id: draft.id, revision: 2, candidateId: draft.candidate!.id, scene: emptyScene() }, guard), /旧图稿/);
  draft = await store.action(cwd, "a", "reject", { id: draft.id, revision: 2, candidateId: draft.candidate!.id }, guard) as DiagramDraft;
  assert.equal(draft.scene.elements[0]?.x, 120);
  assert.throws(() => store.tool(cwd, "a", "patch", { id: draft.id, baseRevision: 1, patch: { removeIds: ["input"] } }), /修订/);
  draft = await store.action(cwd, "a", "save", { id: draft.id, revision: 2, path: "diagrams/a.excalidraw" }, guard) as DiagramDraft;
  assert.equal(draft.savedRevision, 2);
  assert.deepEqual((await readDiagram(cwd, draft.path)).scene, draft.scene);
  const newStore = new DiagramStore();
  const restored = await newStore.action(cwd, "a", "open", { path: draft.path }, guard) as DiagramDraft;
  assert.deepEqual(restored.scene, draft.scene);
  assert.equal(restored.diskHash, draft.diskHash);
});

test("diagram HTTP and agent operations share real plugin enablement gates, auth and session checks", async t => {
  const cwd = await mkdtemp(join(tmpdir(), "pi-diagram-bridge-")); t.after(() => rm(cwd, { recursive: true, force: true }));
  const { host } = terminalHost(cwd);
  const bridge = await startBridge(host, new URL("../web/dist", import.meta.url).pathname, new NodeTelemetry({ env: { PI_WEB_SENTRY_ENABLED: "false" }, monitor: false }), { pluginSettingsFile: join(cwd, "plugins.json") }); t.after(() => bridge.close());
  const url = new URL(bridge.url), headers = { Authorization: `Bearer ${url.hash.slice(1)}`, "Content-Type": "application/json", Origin: url.origin };
  const post = (route: string, input: object, extra = {}) => fetch(url.origin + route, { method: "POST", headers: { ...headers, ...extra }, body: JSON.stringify({ sessionId: "terminal-a", ...input }) });
  assert.equal((await post("/api/diagrams/new", {}, { Authorization: "" })).status, 401);
  assert.equal((await post("/api/diagrams/new", {}, { Origin: "https://other.example" })).status, 403);
  assert.equal((await post("/api/diagrams/new", { sessionId: "stale" })).status, 409);
  const tools = diagramTools((...args) => bridge.runPluginTool(...args));
  assert.deepEqual(tools.map(t => t.name), ["excalidraw_read_me", "excalidraw_create_view", "diagram_reference", "diagram_create", "diagram_read", "diagram_patch"]);
  const created = await bridge.runPluginTool(DIAGRAM_PLUGIN, cwd, "terminal-a", "create", { title: "中文图稿", graph }) as { id: string };
  const loaded = await (await post("/api/diagrams/get", { id: created.id })).json(); assert.equal(loaded.title, "中文图稿");
  const missing = await post("/api/diagrams/get", { id: "expired" });
  assert.equal(missing.status, 404); assert.equal((await missing.json()).reason, "diagram_unavailable");
  const invalid = await post("/api/diagrams/get", { id: "../invalid" });
  assert.equal(invalid.status, 400); assert.equal((await invalid.json()).reason, undefined);
  const big = { ...emptyScene(), elements: Array.from({ length: 100 }, (_, i) => ({ id: `n${i}`, type: "text", text: "文".repeat(400), x: 0, y: i * 50, width: 100, height: 30 })) };
  assert.ok(Buffer.byteLength(JSON.stringify(big)) > 64 * 1024);
  assert.equal((await post("/api/diagrams/import", { scene: big })).status, 200);
  const catalog = await fetch(url.origin + "/api/plugin-management", { headers }).then(r => r.json());
  assert.equal((await post("/api/plugin-management", { id: DIAGRAM_PLUGIN, enabled: false, expected: catalog.revision })).status, 200);
  assert.equal((await post("/api/diagrams/list", {})).status, 403);
  assert.equal((await post("/api/plugin-action", { pluginId: DIAGRAM_PLUGIN, action: "list" })).status, 403);
  await assert.rejects(bridge.runPluginTool(DIAGRAM_PLUGIN, cwd, "terminal-a", "read", { id: created.id }), /停用/);
});
