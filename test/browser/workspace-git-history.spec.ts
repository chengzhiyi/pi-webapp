import { test, expect } from "@playwright/test";
import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { startBridge } from "../../extension/bridge.ts";
import { NodeTelemetry } from "../../extension/telemetry.ts";
import { terminalHost } from "../helpers/terminal-host.ts";

for (const width of [1440, 1024, 768, 390, 320]) test(`Git history, graph, merge details and navigation at ${width}px`, async ({ page }, testInfo) => {
  test.setTimeout(40000);
  const cwd = await mkdtemp(join(tmpdir(), "pi-history-browser-"));
  const empty = await mkdtemp(join(tmpdir(), "pi-history-empty-"));
  const git = async (...args: string[]) => (await promisify(execFile)("git", ["-c", "user.name=History Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false", ...args], { cwd })).stdout.trim();
  await git("init", "-b", "main"); await promisify(execFile)("git", ["init", "-b", "main"], { cwd: empty });
  await writeFile(join(cwd, "base.txt"), "initial content\n"); await git("add", "."); await git("commit", "-m", "Initial <script>\n\nFull original message");
  for (let index = 0; index < 51; index++) await git("commit", "--allow-empty", "-m", `Earlier ${index}`);
  await git("switch", "-c", "feature"); await writeFile(join(cwd, "功能 文件.txt"), "feature content\n"); await git("add", "."); await git("commit", "-m", "Feature change");
  const feature = await git("rev-parse", "HEAD"); await git("tag", "-a", "v1", "-m", "release");
  await git("switch", "main"); await writeFile(join(cwd, "main.txt"), "main content\n"); await git("add", "."); await git("commit", "-m", "Main change");
  const main = await git("rev-parse", "HEAD"); await git("merge", "--no-ff", "feature", "-m", "Merge feature\n\nComplete merge message <script>literal text</script>");
  const merge = await git("rev-parse", "HEAD"); await git("update-ref", "refs/remotes/origin/main", merge);
  await writeFile(join(cwd, "功能 文件.txt"), "WORKING TREE CONTENT\n");
  const indexBefore = await readFile(join(cwd, ".git/index"));
  const { host, switchSession } = terminalHost(cwd);
  const bridge = await startBridge(host, fileURLToPath(new URL("../../web/dist/", import.meta.url)), new NodeTelemetry({ env: { PI_WEB_SENTRY_ENABLED: "false" }, monitor: false }));
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const requests: string[] = []; page.on("request", request => { if (request.url().includes("/api/workspace/git/")) requests.push(request.url()); });
  await page.addInitScript(theme => { localStorage.setItem("pi-web-locale", "en"); localStorage.setItem("pi-web-theme", theme); }, width < 768 ? "dark" : "light");
  await page.setViewportSize({ width, height: 900 });
  const rightbar = page.locator("[data-sidebar-right-session]");
  const history = rightbar.getByRole("list", { name: "Commit history", exact: true });
  const gitTab = () => rightbar.getByRole("tab").filter({ hasText: /^Git$/ });
  const returnToHistory = async () => { await gitTab().focus(); await gitTab().press("Enter"); };
  try {
    await page.goto(bridge.url); await page.getByRole("button", { name: "Open right sidebar", exact: true }).click();
    await rightbar.getByRole("button", { name: "Git changes", exact: true }).click();
    await rightbar.getByRole("button", { name: "History", exact: true }).click();
    await expect(history.getByRole("button")).toHaveCount(50);
    await expect(history.locator(`[data-git-graph-row="${merge}"] [data-parent]`)).toHaveCount(2);
    await expect(history).toContainText("remote: origin/main"); await expect(history).toContainText("tag: v1");
    await page.screenshot({ path: testInfo.outputPath(`history-${width}.png`) });
    await rightbar.getByRole("button", { name: "Load more commits", exact: true }).click();
    await expect(history.getByRole("button")).toHaveCount(55);
    await rightbar.getByRole("button", { name: "Refresh history", exact: true }).click();
    await expect(history.getByRole("button")).toHaveCount(55);
    const mergeRow = history.locator(`[data-commit="${merge}"]`); await mergeRow.focus(); await mergeRow.press("Enter");
    await expect(rightbar.getByRole("heading", { name: "Merge feature", exact: true })).toBeVisible();
    await expect(rightbar.getByLabel("Full commit message", { exact: true })).toContainText("<script>literal text</script>");
    const files = rightbar.getByRole("region", { name: "Commit files", exact: true });
    await expect(files).toContainText("功能 文件.txt");
    await page.screenshot({ path: testInfo.outputPath(`commit-${width}.png`) });
    await rightbar.getByRole("combobox", { name: "Compare parent", exact: true }).selectOption("1");
    await expect(files).toContainText("main.txt"); await expect(files).not.toContainText("功能 文件.txt");
    const tabsBeforeDiff = await rightbar.getByRole("tab").count();
    await rightbar.getByRole("button", { name: "View commit diff: main.txt", exact: true }).click();
    await expect(rightbar.getByRole("tab")).toHaveCount(tabsBeforeDiff);
    await expect(files).toBeVisible();
    await expect(rightbar.getByRole("region", { name: "File diff", exact: true })).toContainText("+main content");
    await returnToHistory(); await history.locator(`[data-commit="${feature}"]`).click();
    await rightbar.getByRole("button", { name: "View commit diff: 功能 文件.txt", exact: true }).click();
    const diff = rightbar.getByRole("region", { name: "File diff", exact: true });
    await expect(diff).toContainText("+feature content"); await expect(diff).not.toContainText("WORKING TREE CONTENT");
    await page.screenshot({ path: testInfo.outputPath(`commit-diff-${width}.png`) });
    await returnToHistory(); await history.locator(`[data-commit="${merge}"]`).click();
    await rightbar.getByRole("button", { name: `Open parent 1: ${main.slice(0, 7)}`, exact: true }).click();
    await expect(rightbar.getByRole("heading", { name: "Main change", exact: true })).toBeVisible();
    await returnToHistory();
    if (width === 1440) {
      await rightbar.getByRole("button", { name: "Fullscreen", exact: true }).click(); await expect(rightbar).toHaveAttribute("data-sidebar-right-panel", "fullscreen");
      await page.screenshot({ path: testInfo.outputPath("history-fullscreen.png") });
      await rightbar.getByRole("button", { name: "Exit fullscreen", exact: true }).click();
      const session = switchSession("history-b", empty); bridge.publish({ type: "snapshot", session });
      await page.getByRole("button", { name: "Open right sidebar", exact: true }).click(); await rightbar.getByRole("button", { name: "Git changes", exact: true }).click();
      await rightbar.getByRole("button", { name: "History", exact: true }).click(); await expect(rightbar.getByText("This repository has no commits yet.", { exact: true })).toBeVisible();
      bridge.publish({ type: "snapshot", session: switchSession("terminal-a", cwd) });
      await expect(rightbar.getByRole("button", { name: "History", exact: true })).toHaveAttribute("aria-pressed", "true");
      await expect(history.getByRole("button")).toHaveCount(55); await expect(history.locator(`[data-commit="${merge}"]`)).toHaveAttribute("aria-current", "true");
      await git("commit", "--allow-empty", "-m", "Newest commit");
      await rightbar.getByRole("button", { name: "Refresh history", exact: true }).click();
      await expect(history.getByRole("button")).toHaveCount(50); await expect(history).toContainText("Newest commit");
      await git("tag", "refs-changed"); await rightbar.getByRole("button", { name: "Load more commits", exact: true }).click();
      await expect(rightbar.getByText("Could not read history, or refs changed.", { exact: false })).toBeVisible();
      await rightbar.getByRole("button", { name: "Retry", exact: true }).click();
      await expect(rightbar.getByText("Could not read history, or refs changed.", { exact: false })).toHaveCount(0);
      await rightbar.getByRole("button", { name: "Load more commits", exact: true }).click(); await expect(history.getByRole("button")).toHaveCount(56);
      await rightbar.getByRole("button", { name: "Collapse right sidebar", exact: true }).click();
      await page.waitForTimeout(200); const count = requests.length; await page.waitForTimeout(5200); expect(requests.length).toBe(count);
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    expect(errors).toEqual([]);
    expect(await readFile(join(cwd, ".git/index"))).toEqual(indexBefore);
    expect(await readFile(join(cwd, "功能 文件.txt"), "utf8")).toBe("WORKING TREE CONTENT\n");
  } finally { await bridge.close(); await rm(cwd, { recursive: true, force: true }); await rm(empty, { recursive: true, force: true }); }
});
